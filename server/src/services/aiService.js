/**
 * Validates and normalizes AI generated recipe structure
 */
const validateAndFormatRecipe = (raw, requestedCuisine = 'International') => {
  if (!raw || typeof raw !== 'object') {
    throw new Error('Invalid recipe object from AI provider');
  }

  const title = raw.title || 'Chef Crafted Pantry Creation';
  const slug = (raw.slug || title.toLowerCase().replace(/[^\w\s-]/g, '').replace(/\s+/g, '-')) + '-ai-' + Date.now().toString(36);
  const cuisine = raw.cuisine || requestedCuisine || 'International';

  const ingredients = Array.isArray(raw.ingredients)
    ? raw.ingredients.map(i => ({
        name: typeof i === 'string' ? i : (i.name || 'Ingredient'),
        quantity: typeof i === 'object' && i.quantity ? Number(i.quantity) : 1,
        unit: typeof i === 'object' && i.unit ? i.unit : 'unit',
        notes: typeof i === 'object' && i.notes ? i.notes : '',
        category: (typeof i === 'object' && i.category) || 'Pantry & Grains'
      }))
    : [];

  const instructions = Array.isArray(raw.instructions)
    ? raw.instructions.map((step, idx) => ({
        stepNumber: idx + 1,
        title: typeof step === 'object' && step.title ? step.title : `Step ${idx + 1}`,
        instruction: typeof step === 'string' ? step : (step.instruction || step.text || ''),
        timerMinutes: typeof step === 'object' && step.timerMinutes ? Number(step.timerMinutes) : null,
        temperature: typeof step === 'object' && step.temperature ? step.temperature : ''
      }))
    : [];

  return {
    title,
    slug,
    description: raw.description || `A bespoke ${cuisine} dish crafted using your available pantry ingredients.`,
    cuisine,
    country: raw.country || cuisine,
    mealType: Array.isArray(raw.mealType) ? raw.mealType : ['Dinner', 'Lunch'],
    prepTime: Number(raw.prepTime) || 15,
    cookTime: Number(raw.cookTime) || 20,
    totalTime: (Number(raw.prepTime) || 15) + (Number(raw.cookTime) || 20),
    servings: Number(raw.servings) || 4,
    difficulty: raw.difficulty && ['Easy', 'Medium', 'Hard'].includes(raw.difficulty) ? raw.difficulty : 'Medium',
    ingredients,
    instructions,
    dietary: Array.isArray(raw.dietary) ? raw.dietary : [],
    allergens: Array.isArray(raw.allergens) ? raw.allergens : [],
    cookingTips: Array.isArray(raw.cookingTips) ? raw.cookingTips : ['Adjust seasoning to personal taste before serving.'],
    variations: Array.isArray(raw.variations) ? raw.variations : ['Feel free to swap proteins or vegetables based on seasonal availability.'],
    nutrition: {
      calories: Number(raw.nutrition?.calories) || 420,
      protein: Number(raw.nutrition?.protein) || 24,
      carbs: Number(raw.nutrition?.carbs) || 45,
      fat: Number(raw.nutrition?.fat) || 16,
      fiber: Number(raw.nutrition?.fiber) || 4,
      isVerified: false
    },
    image: {
      url: CUISINE_DEFAULT_IMAGES[cuisine] || CUISINE_DEFAULT_IMAGES.Default,
      alt: title,
      attribution: 'Unsplash Culinary Collection',
      creditUrl: 'https://unsplash.com'
    },
    rating: 4.8,
    reviewsCount: 1,
    isAiGenerated: true,
    foodSafetyNotice: 'This recipe was generated by AI based on your pantry. Please verify internal cooking temperatures (e.g. poultry 75°C / 165°F) and allergen guidelines.'
  };
};

