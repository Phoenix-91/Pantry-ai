/**
 * Main AI Generation Function
 */
export const generateAIRecipes = async ({
  ingredients = [],
  cuisine = 'International',
  dietary = [],
  maxTime = 45,
  difficulty = 'Medium',
  allergies = []
}) => {
  const geminiKey = process.env.GEMINI_API_KEY;
  const openAiKey = process.env.OPENAI_API_KEY;

  const prompt = `You are an elite master chef and food scientist.
A home cook has the following ingredients in their kitchen: ${ingredients.join(', ')}.
Requested Cuisine: ${cuisine || 'Any'}.
Dietary Preferences: ${dietary.length > 0 ? dietary.join(', ') : 'None'}.
Maximum Total Time: ${maxTime} minutes.
Difficulty Level: ${difficulty}.
Allergies / Dislikes to Avoid: ${allergies.length > 0 ? allergies.join(', ') : 'None'}.

Generate 1 creative, authentic, and realistic recipe that maximizes the user's available ingredients.
Respond ONLY with a valid JSON object matching this exact schema:
{
  "title": "string",
  "description": "string (short introduction and flavor profile)",
  "cuisine": "${cuisine || 'International'}",
  "country": "string",
  "prepTime": number,
  "cookTime": number,
  "servings": number,
  "difficulty": "Easy" | "Medium" | "Hard",
  "ingredients": [
    { "name": "string", "quantity": number, "unit": "string", "notes": "string", "category": "Produce" | "Pantry & Grains" | "Meat & Seafood" | "Dairy & Eggs" | "Spices & Seasonings" | "Baking & Sweeteners" | "Bakery" | "Other" }
  ],
  "instructions": [
    { "stepNumber": number, "title": "string", "instruction": "string", "timerMinutes": number | null, "temperature": "string" }
  ],
  "dietary": ["string"],
  "allergens": ["string"],
  "cookingTips": ["string"],
  "variations": ["string"],
  "nutrition": { "calories": number, "protein": number, "carbs": number, "fat": number, "fiber": number }
}`;

  // 1. Try Gemini API if key is configured
  if (geminiKey) {
    try {
      console.log('[AI Service] Calling Gemini API for recipe generation...');
      const controller = new AbortController();
      const timeoutId = setTimeout(() => controller.abort(), 8000);

      const endpoint = `https://generativelanguage.googleapis.com/v1beta/models/gemini-1.5-flash:generateContent?key=${geminiKey}`;
      const response = await fetch(endpoint, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          contents: [{ parts: [{ text: prompt }] }],
          generationConfig: { responseMimeType: 'application/json' }
        }),
        signal: controller.signal
      });

      clearTimeout(timeoutId);

      if (response.ok) {
        const data = await response.json();
        const text = data.candidates?.[0]?.content?.parts?.[0]?.text;
        if (text) {
          const parsed = JSON.parse(text);
          return [validateAndFormatRecipe(parsed, cuisine)];
        }
      } else {
        console.warn(`[AI Service] Gemini API returned status ${response.status}. Using culinary engine fallback...`);
      }
    } catch (err) {
      console.warn(`[AI Service] Gemini request error (${err.message}). Using culinary engine fallback...`);
    }
  }

  // 2. Try OpenAI API if key is configured
  if (openAiKey) {
    try {
      console.log('[AI Service] Calling OpenAI API for recipe generation...');
      const controller = new AbortController();
      const timeoutId = setTimeout(() => controller.abort(), 8000);

      const response = await fetch('https://api.openai.com/v1/chat/completions', {
        method: 'POST',
        headers: {
          'Content-Type': 'application/json',
          'Authorization': `Bearer ${openAiKey}`
        },
        body: JSON.stringify({
          model: 'gpt-3.5-turbo',
          messages: [{ role: 'user', content: prompt }],
          response_format: { type: 'json_object' }
        }),
        signal: controller.signal
      });

      clearTimeout(timeoutId);

      if (response.ok) {
        const data = await response.json();
        const content = data.choices?.[0]?.message?.content;
        if (content) {
          const parsed = JSON.parse(content);
          return [validateAndFormatRecipe(parsed, cuisine)];
        }
      } else {
        console.warn(`[AI Service] OpenAI API returned status ${response.status}. Using culinary engine fallback...`);
      }
    } catch (err) {
      console.warn(`[AI Service] OpenAI request error (${err.message}). Using culinary engine fallback...`);
    }
  }

  // 3. Built-in Culinary Synthesis Fallback
  console.log('[AI Service] Using Built-in Culinary Synthesis Engine.');
  const synthesized = synthesizeLocalRecipe({ ingredients, cuisine, dietary, maxTime });
  return [synthesized];
};
